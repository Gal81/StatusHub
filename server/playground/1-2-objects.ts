// -----------------------------------------------------------------------------
// Шаг 1. Описываем форму объекта через `type`
// -----------------------------------------------------------------------------

// В уроке 1.1 типы были у отдельных значений: number, string...
// Но в StatusHub данные приходят «пачками»: у сайта есть id, адрес, название,
// дата добавления. Хочется один раз описать, КАК выглядит объект-сайт,
// и дальше требовать эту форму везде, где сайт используется.
//
// `type Имя = { ... }` — это type alias («псевдоним типа»): мы даём имя
// описанию формы объекта. Само описание — список полей и их типов.
// В рантайме от этой конструкции ничего не остаётся (node её просто стирает) —
// это чисто «чертёж» для проверки.
type Site = {
  // readonly — поле можно задать при создании объекта, но нельзя менять потом.
  // id сайта не должен меняться никогда: по нему мы будем находить сайт,
  // и если его случайно перезаписать — потеряем связь с данными.
  readonly id: string

  // Обычное обязательное поле: без него объект не считается Site.
  url: string

  // `?` — необязательное поле: его можно вообще не указывать.
  // Пользователь может добавить сайт просто по URL, без названия.
  name?: string

  // Date — встроенный в JavaScript класс для даты и времени.
  // Его можно использовать как тип: «здесь лежит объект Date».
  // Дата добавления тоже не меняется → readonly.
  readonly createdAt: Date
}

// --- Массив объектов ---
// `Site[]` читается как «массив, каждый элемент которого — Site».
// Аннотация здесь полезна (хотя TypeScript и мог бы вывести тип сам):
// мы заранее говорим, ЧТО должно лежать в массиве, и TypeScript проверит
// каждый объект — опечатку в поле или забытый url он подсветит прямо тут,
// а не где-то далеко, где массив используется.
const sites: Site[] = [
  {
    id: '1',
    url: 'https://example.com',
    name: 'Example', // название указали
    createdAt: new Date('2026-11-01'),
  },
  {
    id: '2',
    url: 'https://nodejs.org',
    // name не указали — это нормально, поле необязательное
    createdAt: new Date('2026-11-10'),
  },
]

// --- Функция, которая печатает список ---
// Параметр типизирован как Site[] (помним из 1.1: параметрам тип пишем всегда).
// Функции подробно разберём в уроке 1.4.
function printSites(list: Site[]) {
  // for...of — обычный JavaScript-цикл «для каждого элемента массива».
  // TypeScript знает, что list — это Site[], значит site внутри — Site.
  // 👉 Наведи курсор на `site`: увидишь `const site: Site`.
  for (const site of list) {
    // site.name имеет тип `string | undefined` — его может не быть.
    // `??` (nullish coalescing, обычный JS): «возьми левое, а если там
    // undefined или null — возьми правое». Так мы показываем URL вместо
    // отсутствующего названия, а не печатаем слово "undefined".
    const title = site.name ?? site.url

    // toLocaleDateString() — метод Date: дата в читаемом виде, без времени.
    // TypeScript подскажет этот метод в автодополнении, потому что знает,
    // что createdAt — Date. 👉 Поставь точку после `site.createdAt` и посмотри.
    console.log(`#${site.id}  ${title}  (${site.url}), добавлен ${site.createdAt.toLocaleDateString()}`)
  }
}

printSites(sites)

// -----------------------------------------------------------------------------
// Шаг 2. Ломаем объекты: какие ошибки выдаёт TypeScript
// -----------------------------------------------------------------------------

// Здесь несколько ошибок СПЕЦИАЛЬНО. Чтобы файл всё равно проходил `tsc`,
// над каждой стоит комментарий `// @ts-expect-error`. Он означает:
// «я ЗНАЮ, что на следующей строке ошибка типа, — не ругайся».
// Причём это ещё и проверка: если ошибки на строке НЕ окажется, tsc выдаст
// «Unused '@ts-expect-error' directive». То есть мы фиксируем, что TypeScript
// действительно ловит эти случаи.
//
// 👉 Чтобы увидеть сам текст ошибки — удали строку с `@ts-expect-error`
//    над интересующим местом (или наведи на подчёркнутое в редакторе),
//    потом верни обратно.

// Отдельный сайт для экспериментов.
const site: Site = {
  id: '3',
  url: 'https://github.com',
  createdAt: new Date(),
}

// --- Ошибка 1. Изменение readonly-поля ---
// TS2540: Cannot assign to 'id' because it is a read-only property.
// @ts-expect-error
site.id = '999'

// Важно: readonly — это ТОЛЬКО проверка типов. Node стирает типы (помним 1.1),
// поэтому в рантайме присваивание выше реально выполнилось!
// Мы подавили ошибку — и id действительно поменялся:
console.log('id после «запрещённого» присваивания:', site.id) // → 999
// Вывод: readonly защищает от ошибки программиста ДО запуска, но не
// «замораживает» объект во время работы программы.
// (Для настоящей заморозки в JS есть Object.freeze — нам пока не нужно.)

// --- Ошибка 2. Лишнее поле ---
// TS2353: Object literal may only specify known properties,
//         and 'status' does not exist in type 'Site'.
// Зачем TypeScript это ловит: лишнее поле чаще всего — опечатка
// (например, `nmae` вместо `name`) или поле, которое мы забыли описать в типе.
const withExtra: Site = {
  id: '4',
  url: 'https://example.org',
  createdAt: new Date(),
  // @ts-expect-error
  status: 'up',
}

// Нюанс: эта проверка (excess property check) срабатывает только для объекта,
// написанного ПРЯМО на месте ({ ... }). Если объект сначала лежит в отдельной
// переменной, лишние поля пропускаются — TypeScript проверяет лишь, что все
// НУЖНЫЕ поля есть. Так что «лишнее поле» — подсказка от опечаток,
// а не строгий запрет.
const raw = { id: '5', url: 'https://example.net', createdAt: new Date(), status: 'up' }
const fromVariable: Site = raw // ошибки нет

// --- Ошибка 3. Не хватает обязательного поля ---
// TS2741: Property 'url' is missing in type '{ ... }' but required in type 'Site'.
// @ts-expect-error
const withoutUrl: Site = {
  id: '6',
  createdAt: new Date(),
}

// --- name?: string  против  name: string | undefined ---
// В tsconfig включён `exactOptionalPropertyTypes`, и разница становится строгой:
//
//   name?: string              → поля МОЖНО НЕ БЫТЬ, но если оно есть — это string.
//                                Явно написать `name: undefined` НЕЛЬЗЯ.
//   name: string | undefined   → поле ОБЯЗАНО быть, но значение может быть undefined.
//
// Зачем такая строгость: «поля нет» и «поле есть, но пустое» — разные вещи.
// Например, позже при обновлении сайта «name не передали» будет значить
// «не трогай название», а «name: undefined» могло бы случайно его стереть.

// TS2375: Type '{ ... name: undefined }' is not assignable to type 'Site'
//         with 'exactOptionalPropertyTypes: true'.
// @ts-expect-error
const explicitUndefined: Site = { id: '7', url: 'https://a.com', name: undefined, createdAt: new Date() }

// Для сравнения — тип, где поле обязательно, но может быть undefined:
type SiteWithRequiredName = {
  id: string
  name: string | undefined
}
const ok: SiteWithRequiredName = { id: '8', name: undefined } // так можно
// TS2741: Property 'name' is missing...
// @ts-expect-error
const missing: SiteWithRequiredName = { id: '9' } // а так — нет: поле обязано быть

console.log({ withExtra, fromVariable, withoutUrl, explicitUndefined, ok, missing })

// -----------------------------------------------------------------------------
// Шаг 3. `interface` против `type`
// -----------------------------------------------------------------------------

// Тот же сайт, описанный через interface. Синтаксис почти одинаковый:
// нет `=`, вместо `type Имя = { ... }` пишем `interface Имя { ... }`.
// Для формы объекта они взаимозаменяемы — объект `site` подходит под оба.
interface SiteShape {
  readonly id: string
  url: string
  name?: string
  readonly createdAt: Date
}

const sameSite: SiteShape = site // ок: форма та же, TypeScript сравнивает по полям
// Это важное свойство TypeScript — структурная типизация: тип проверяется
// по набору полей, а не по имени. Site и SiteShape — разные имена одной формы.

// --- Расширение: interface — через extends, type — через & ---
// Задача: сайт + результаты последней проверки.

// interface: «возьми всё из SiteShape и добавь поля».
interface CheckedSiteShape extends SiteShape {
  lastStatusCode: number
}

// type: `&` — intersection («пересечение»): объект должен иметь поля
// И из Site, И из { lastStatusCode }. Результат тот же.
type CheckedSite = Site & {
  lastStatusCode: number
}

const checked1: CheckedSiteShape = { ...site, lastStatusCode: 200 }
const checked2: CheckedSite = { ...site, lastStatusCode: 200 }
// `...site` (spread, обычный JS) — скопировать все поля site в новый объект.

// --- Что умеет только interface: слияние объявлений (declaration merging) ---
// Если объявить interface с тем же именем ещё раз, TypeScript НЕ ругается,
// а склеивает их в один. Теперь в SiteShape есть ещё и поле tags.
interface SiteShape {
  tags?: string[]
}
// Где это полезно: дописать поля в чужой тип (например, библиотека Fastify
// так позволяет добавлять свои поля к запросу — увидим в этапе 3).
// Где это опасно: случайно назвать два interface одинаково и незаметно
// получить смесь полей. С `type` повторное имя — сразу ошибка.

// --- Что умеет только type: любые типы, а не только объекты ---
// type может дать имя чему угодно: union, литералу, примитиву.
// interface описывает ТОЛЬКО форму объекта.
type SiteId = string // псевдоним для примитива
type CheckStatus = 'up' | 'down' // union из литералов — подробно в уроке 1.3
// interface CheckStatus = 'up' | 'down'  ← так нельзя, это синтаксическая ошибка

const statusExample: CheckStatus = 'up'
const idExample: SiteId = 'abc'

// --- Выбор для StatusHub: `type` ---
// Почему:
// 1. Нам всё равно нужен type для union-типов (статусы, HTTP-методы — урок 1.3),
//    а enum в проекте запрещён. Удобно писать всё одним способом.
// 2. Нет случайного слияния объявлений.
// 3. «Дописывать чужие типы» нам пока не нужно; когда понадобится
//    (расширение типов Fastify) — там interface и используем, осознанно.
// Оба варианта нормальны, главное — единообразие внутри проекта.

console.log({ sameSite, checked1, checked2, statusExample, idExample })

// =============================================================================
// Вопросы для самопроверки (урок 1.2)
// =============================================================================
//
// 1. Чем `name?: string` отличается от `name: string | undefined`?
//    `name?: string` — поля может не быть; если есть — это строка.
//    `name: string | undefined` — поле обязано быть, но значение может быть
//    undefined. С exactOptionalPropertyTypes записать `name: undefined`
//    в необязательное поле нельзя — «нет поля» и «пустое поле» различаются.
//
// 2. Защищает ли `readonly` объект во время выполнения программы?
//    Нет. Это только проверка типов; node стирает типы, и присваивание
//    в рантайме выполнится (см. шаг 2: id стал '999').
//
// 3. Что умеет interface, чего не умеет type, и наоборот?
//    interface: слияние объявлений (можно дописать поля к существующему).
//    type: имя для любого типа — union, литерал, примитив, пересечение.
//    Для обычной формы объекта они взаимозаменяемы.
