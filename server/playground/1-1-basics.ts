// =============================================================================
// Урок 1.1. Типы, аннотации и вывод типов
// Запуск:          node playground/1-1-basics.ts   (из папки server)
// Проверка типов:  npx tsc -p playground
// =============================================================================

// -----------------------------------------------------------------------------
// Шаг 1. Базовые типы, аннотация и вывод типа
// -----------------------------------------------------------------------------

// TypeScript = JavaScript + описание того, какие значения где допустимы.
// Это описание (тип) проверяется ДО запуска программы — редактором и `tsc`.
//
// Базовые (примитивные) типы — те же, что и в JS:
//   string    — текст
//   number    — любое число (целое и дробное — один тип, отдельного int нет)
//   boolean   — true / false
//   null      — «значения нет» (ставим осознанно)
//   undefined — «значение не задано» (так бывает «само»: пустая переменная,
//               отсутствующее поле объекта)

// --- Аннотация: тип пишем явно, после двоеточия ---
// Читается как «переменная port, у которой тип number, равна 3000».
let port: number = 3000

// --- Вывод типа (type inference): тип не пишем, TypeScript догадывается сам ---
// Справа стоит число → значит port2 тоже number. Аннотация тут ничего не добавляет,
// поэтому в реальном коде так и пишут — без неё.
// 👉 Наведи курсор на `port2` в редакторе: увидишь `let port2: number`.
let port2 = 3000

// Тип закрепляется за переменной навсегда. Менять ЗНАЧЕНИЕ можно,
// менять ТИП — нельзя:
port = 8080 // ок: число на число
port2 = 8081 // ок
// port2 = '8081' // ❌ раскомментируй — редактор подчеркнёт: string нельзя положить в number

// Ещё несколько примеров вывода. Везде наведи курсор — тип виден без аннотаций.
let siteName = 'Example' // string
let isUp = true // boolean
let responseTimeMs = 120.5 // number (дробное — всё равно number)

// -----------------------------------------------------------------------------
// let vs const: «широкий» и «узкий» тип
// -----------------------------------------------------------------------------

// `let` — переменную можно перезаписать. Поэтому TypeScript выводит ШИРОКИЙ тип:
// раз сюда потом могут положить другую строку — тип просто `string`.
// 👉 Наведи курсор: `let letStatus: string`
let letStatus = 'up'
letStatus = 'down' // ок, это тоже string
letStatus = 'что угодно' // тоже ок — TypeScript не знает, что статусов всего два

// `const` — переменную перезаписать нельзя. Значит, в ней НАВСЕГДА лежит 'up',
// и TypeScript выводит УЗКИЙ тип — не «какая-то строка», а ровно 'up'.
// Такой тип называется literal type (тип-литерал): само значение служит типом.
// 👉 Наведи курсор: `const constStatus: "up"`
const constStatus = 'up'

// Зачем это знать? Позже (урок 1.3) мы опишем тип статуса как 'up' | 'down',
// и разница между let/const начнёт влиять на то, примет ли TypeScript значение.
// Пока достаточно запомнить: const → тип = само значение, let → общий тип.

// Чтобы файл при запуске что-то показал (и чтобы линтер/редактор не ругался
// на «объявлена, но не используется»), печатаем значения.
console.log({ port, port2, siteName, isUp, responseTimeMs, letStatus, constStatus })

// -----------------------------------------------------------------------------
// Шаг 2. Ошибка типа: tsc её видит, а node всё равно запускает файл
// -----------------------------------------------------------------------------

// Таймаут проверки сайта в миллисекундах — по смыслу это число.
let timeoutMs = 5000

// ❌ Намеренная ошибка: кладём строку в переменную типа number.
// Редактор подчеркнёт эту строку красным, `npx tsc -p playground` выдаст ошибку
// TS2322: Type 'string' is not assignable to type 'number'.
// ✅ Исправлено в шаге 3: таймаут — число миллисекунд. Старую строку оставили
// закомментированной — раскомментируй, если захочешь снова увидеть ошибку.
// timeoutMs = '10 секунд'
//
// `10_000` — то же самое, что 10000; подчёркивание просто разделяет разряды
// для читаемости (это обычный JavaScript, не TypeScript).
timeoutMs = 10_000

// А теперь самое важное: `node playground/1-1-basics.ts` всё равно выполнит файл.
//
// Почему? Node.js «запускает TypeScript» очень просто: он СТИРАЕТ все типы
// (`: number`, `type ...`, `interface ...`) и выполняет то, что осталось, —
// обычный JavaScript. Проверять типы Node не умеет и не пытается.
// Это называется type stripping («срезание типов»).
//
// Поэтому в проекте две разные команды с разной ролью:
//   node — запустить (быстро, без проверки)
//   tsc  — проверить (ничего не запускает, только ищет ошибки)
// Ошибки типов ловят редактор и tsc, а НЕ запуск программы.
//
// Чем это опасно, видно ниже: JavaScript молча посчитает 'строка' * 2 = NaN
// («Not a Number»), и программа продолжит работать с мусором вместо таймаута.
// Именно такие тихие баги TypeScript и должен ловить ДО запуска.
console.log('timeoutMs:', timeoutMs, '| удвоенный таймаут:', timeoutMs * 2)

// -----------------------------------------------------------------------------
// Шаг 3. Где аннотация нужна, а где лишняя
// -----------------------------------------------------------------------------

// Правило: если TypeScript может вывести тип из значения справа — аннотацию
// НЕ пишем. Она только дублирует очевидное и добавляет шум:
//   let retries: number = 3   ← лишнее
//   let retries = 3           ← так лучше
//
// Аннотация нужна там, где TypeScript ВЫВЕСТИ тип НЕ МОЖЕТ (или выведет не тот).
// Три самых частых случая:

// --- Случай 1. Параметры функции ---
// Внутри функции TypeScript не знает, с чем её будут вызывать, — значение
// появится только при вызове. Поэтому тип параметра всегда пишем сами.
// Без `: string` в строгом режиме (`strict: true` в tsconfig) будет ошибка:
// «Parameter 'url' implicitly has an 'any' type».
// (Подробно функции — в уроке 1.4, здесь только про аннотацию.)
function describeSite(url: string) {
  // Тип возвращаемого значения мы НЕ писали — TypeScript вывел его сам: string.
  // 👉 Наведи курсор на `describeSite`: `function describeSite(url: string): string`
  return `Сайт: ${url}`
}

// --- Случай 2. Значение появится позже ---
// Объявляем переменную сейчас, а присвоим потом (например, после проверки сайта).
// Справа значения нет — выводить не из чего, поэтому тип указываем явно.
let lastResponseTimeMs: number
lastResponseTimeMs = 230

// --- Случай 3. Начальное значение «уже» итогового типа ---
// Ошибки пока нет → начинаем с null. Но если написать просто `let lastError = null`,
// TypeScript решит, что тут всегда null, и строку потом положить не даст.
// Поэтому явно говорим: «здесь будет строка ИЛИ null».
// (`|` — это union type, «одно из». Подробно — в уроке 1.3.)
let lastError: string | null = null
lastError = 'Timeout'

console.log(describeSite('https://example.com'), { lastResponseTimeMs, lastError })

// =============================================================================
// Вопросы для самопроверки (урок 1.1)
// =============================================================================
//
// 1. Почему код с ошибкой типов выполняется через `node`?
//    Node.js не проверяет типы: он стирает их (type stripping) и выполняет
//    оставшийся JavaScript. Проверку делают только `tsc` и редактор.
//
// 2. Чем отличается тип `let x = 'up'` от `const x = 'up'`?
//    let → тип `string` (переменную можно перезаписать любой строкой).
//    const → тип-литерал `'up'` (значение не изменится, тип = само значение).
//
// 3. Где аннотации стоит писать всегда, а где лучше довериться выводу?
//    Всегда: параметры функций; переменные без начального значения;
//    переменные, которые позже примут более широкий тип (null → string).
//    Довериться выводу: переменные с понятным значением справа
//    и (чаще всего) возвращаемый тип функции.
