// -----------------------------------------------------------------------------
// Шаг 1. Literal types и union: тип CheckStatus
// -----------------------------------------------------------------------------

// --- Literal type: конкретное значение как тип ---
// Мы уже видели его в 1.1: `const constStatus = 'up'` получил тип не string, а 'up'.
// Такой тип можно написать и явно. Переменная типа 'up' принимает ТОЛЬКО 'up'.
let onlyUp: 'up' = 'up'
// onlyUp = 'down' // ❌ Type '"down"' is not assignable to type '"up"'

// Литералом может быть строка, число или boolean:
let okCode: 200 = 200

// Сам по себе один литерал почти бесполезен — переменная, которая может
// хранить только одно значение. Сила появляется в сочетании с union.

// --- Union type: «одно из» ---
// `A | B` читается «A или B». Значение должно подходить хотя бы под один вариант.
// Union из литералов = ограниченный список допустимых значений.
//
// Какие состояния бывают у проверки сайта в StatusHub:
//   'pending' — проверку ещё не запускали или она идёт
//   'up'      — сайт ответил успешно
//   'down'    — сайт ответил ошибкой (например, 500)
//   'error'   — ответа нет вообще (таймаут, неверный адрес, нет сети)
// Почему 'down' и 'error' отдельно: «сервер сломан» и «до сервера не достучались» —
// разные проблемы, пользователю полезно их различать.
type CheckStatus = 'pending' | 'up' | 'down' | 'error'

// Теперь TypeScript знает весь список и:
// 1) не пропустит значение не из списка;
// 2) подскажет варианты в автодополнении.
// 👉 Сотри 'up' ниже, поставь курсор между кавычками и нажми Ctrl+Space —
//    редактор предложит все четыре статуса.
let status: CheckStatus = 'up'
status = 'down' // ок — значение из списка

// Опечатка или выдуманный статус — ошибка ДО запуска:
// TS2322: Type '"donw"' is not assignable to type 'CheckStatus'.
// @ts-expect-error
status = 'donw'

// Сравни с обычным string: там опечатка прошла бы молча,
// и где-то дальше `if (status === 'down')` просто никогда не сработал бы.
let looseStatus: string = 'up'
looseStatus = 'donw' // ошибки нет — string принимает любую строку

// --- Связь с let/const из урока 1.1 ---
// `let s = 'up'` выводит широкий тип string. Если потом передать s туда,
// где ждут CheckStatus, будет ошибка: string шире, чем список из 4 вариантов.
let inferred = 'up' // string
// @ts-expect-error — TS2322: Type 'string' is not assignable to type 'CheckStatus'.
const fromLet: CheckStatus = inferred

// Решения: использовать const (тип станет литералом 'up', он входит в список)
// или сразу аннотировать переменную как CheckStatus.
const constUp = 'up' // тип 'up'
const fromConst: CheckStatus = constUp // ок

console.log({ onlyUp, okCode, status, looseStatus, fromLet, fromConst })

// -----------------------------------------------------------------------------
// Шаг 2. Union в работе: функция статус → текст, HttpMethod, string | number
// -----------------------------------------------------------------------------

// --- Функция: по статусу вернуть текст для пользователя ---
// Параметр — CheckStatus, поэтому вызвать функцию с 'donw' или с любой
// произвольной строкой нельзя. Ошибка будет в месте ВЫЗОВА, а не где-то внутри.
//
// Возвращаемый тип `: string` здесь написан осознанно (хотя TS вывел бы сам).
// Он даёт полезную проверку — см. «эксперимент» ниже.
function statusToText(status: CheckStatus): string {
  // switch — обычный JS. TypeScript понимает, что в каждом case статус
  // уже конкретный (внутри `case 'up':` тип status — 'up').
  switch (status) {
    case 'pending':
      return 'Проверка ещё не завершена'
    case 'up':
      return 'Сайт доступен'
    case 'down':
      return 'Сайт отвечает с ошибкой'
    case 'error':
      return 'Не удалось связаться с сайтом'
  }
  // После switch кода нет — и TypeScript не ругается, потому что знает:
  // все 4 варианта CheckStatus разобраны, сюда выполнение не дойдёт.
}

// 🧪 Эксперимент: добавь в CheckStatus (шаг 1) пятый статус, например 'paused'.
// TypeScript сразу подсветит statusToText:
//   TS2366: Function lacks ending return statement and return type does
//           not include 'undefined'.
// Т.е. «есть статус, для которого функция ничего не вернёт». Union + явный
// возвращаемый тип = TypeScript напоминает обновить все места, где разбираются
// статусы. Со `string` вместо union такой подсказки не было бы.
// (Не забудь потом убрать 'paused' обратно.)

console.log(statusToText('up'))
console.log(statusToText('error'))
// @ts-expect-error — TS2345: Argument of type '"donw"' is not assignable to parameter of type 'CheckStatus'.
statusToText('donw')

// --- HttpMethod: каким запросом проверяем сайт ---
// GET  — обычный запрос: сервер присылает заголовки И тело (всю страницу).
// HEAD — то же самое, но БЕЗ тела: только статус и заголовки.
//        Для проверки «жив ли сайт» тела не нужно, HEAD экономит трафик и время.
//        Но некоторые серверы HEAD не поддерживают — тогда пригодится GET.
// Других методов (POST, DELETE...) для проверки мы не допускаем — union это фиксирует.
type HttpMethod = 'GET' | 'HEAD'

// Union-тип поля внутри объекта — так он и будет использоваться в проекте.
type CheckConfig = {
  url: string
  method: HttpMethod
  timeoutMs: number
}

const config: CheckConfig = {
  url: 'https://example.com',
  method: 'HEAD',
  timeoutMs: 5000,
}

const badConfig: CheckConfig = {
  url: 'https://example.com',
  // @ts-expect-error — TS2322: Type '"POST"' is not assignable to type 'HttpMethod'.
  method: 'POST',
  timeoutMs: 5000,
}

// --- string | number: что можно делать без проверок ---
// Union из РАЗНЫХ типов: значение может быть строкой ИЛИ числом.
// Пример: id сайта пришёл из разных источников — где-то '42', где-то 42.
//
// Смотрим на ПАРАМЕТР функции: внутри неё TypeScript действительно не знает,
// что передадут, — может быть и то, и другое.
function describeId(id: string | number) {
  // Без проверки можно использовать только то, что есть И у string, И у number.
  // Например, toString() есть у обоих — ок:
  const asText = id.toString()

  // А специфичное для одного типа — нельзя: вдруг там другой?
  // @ts-expect-error — TS2339: Property 'toUpperCase' does not exist on type 'string | number'.
  id.toUpperCase()
  // Если подавить ошибку и вызвать describeId(42), программа упадёт при запуске:
  //   TypeError: id.toUpperCase is not a function
  // Поэтому describeId ниже нигде не вызываем.

  return asText
}

// Нюанс: с переменной TypeScript умнее. После `let siteId: string | number = 42`
// он помнит, что СЕЙЧАС там число, и разрешит siteId.toFixed() — пока
// в siteId не положат что-то другое. 👉 Наведи курсор на siteId во второй строке.
let siteId: string | number = 42
console.log(siteId.toFixed(1)) // ок: TypeScript видит, что там сейчас 42

// Чтобы использовать «особые» методы, нужно сначала проверить, что внутри.
// Проверка typeof сужает тип внутри if — это называется narrowing,
// подробно в уроке 1.5. Здесь — только чтобы показать идею:
function formatId(id: string | number): string {
  if (typeof id === 'number') {
    // здесь TypeScript знает: id — number
    return id.toFixed(0)
  }
  // а здесь — string (number уже отсечён проверкой выше)
  return id.toUpperCase()
}

console.log(formatId(42), formatId('abc'), { config, badConfig })

// -----------------------------------------------------------------------------
// Шаг 3. Почему в проекте нет enum
// -----------------------------------------------------------------------------

// enum — конструкция TypeScript для «списка именованных значений».
// Во многих проектах статусы описали бы так:
//
//   enum CheckStatusEnum {
//     Up = 'up',
//     Down = 'down',
//   }
//   const s = CheckStatusEnum.Up
//
// В этом файле так написать нельзя (поэтому код выше — в комментарии):
//
//   tsc:  TS1294: This syntax is not allowed when 'erasableSyntaxOnly' is enabled.
//   node: SyntaxError [ERR_UNSUPPORTED_TYPESCRIPT_SYNTAX]:
//         TypeScript enum is not supported in strip-only mode
//
// (Оба сообщения настоящие — проверено на временном файле.)
//
// --- В чём принципиальная разница ---
// Всё, что мы писали до сих пор (`: string`, `type`, `interface`, `'up' | 'down'`),
// существует ТОЛЬКО для проверки. Node просто стирает это — и остаётся
// рабочий JavaScript. Стёрли `: CheckStatus` → `let status = 'up'`. Всё.
//
// enum — не просто тип. Он СОЗДАЁТ значение: объект, который существует
// во время работы программы (иначе откуда взялось бы `CheckStatusEnum.Up`?).
// Чтобы enum заработал, TypeScript должен СГЕНЕРИРОВАТЬ JavaScript-код,
// примерно такой:
//
//   var CheckStatusEnum;
//   (function (CheckStatusEnum) {
//     CheckStatusEnum["Up"] = "up";
//     CheckStatusEnum["Down"] = "down";
//   })(CheckStatusEnum || (CheckStatusEnum = {}));
//
// Если enum просто «стереть», `CheckStatusEnum.Up` будет ссылаться на
// несуществующий объект. А Node в режиме type stripping только стирает типы
// и ничего не генерирует — поэтому enum ему не под силу.
//
// Флаг `erasableSyntaxOnly` в tsconfig заставляет tsc заранее запрещать
// всё «нестираемое» (enum, namespace, parameter properties в классах), чтобы
// мы узнали о проблеме в редакторе, а не при запуске.
//
// --- Чем заменяем ---
// Union из литералов (шаг 1) делает ту же работу:
//   - ограниченный список значений        ✅
//   - ошибка на опечатке                    ✅
//   - автодополнение                        ✅
//   - TS2366, если забыли обработать статус ✅ (шаг 2)
// И при этом полностью стирается. В коде пишем просто 'up', а не CheckStatusEnum.Up.
//
// Чего union НЕ даёт: списка значений во время работы программы (например,
// чтобы показать все статусы в выпадающем списке). Если такое понадобится —
// заведём обычный массив и выведем тип из него; это разберём, когда дойдём.

// =============================================================================
// Вопросы для самопроверки (урок 1.3)
// =============================================================================
//
// 1. Чем `string` отличается от `'up' | 'down'` с точки зрения безопасности?
//    string принимает любую строку: опечатка 'donw' пройдёт молча, и баг
//    проявится только при работе (условие `=== 'down'` просто не сработает).
//    Union разрешает только перечисленные значения — опечатка будет ошибкой
//    типа ДО запуска, плюс TS подскажет, если какой-то вариант не обработан.
//
// 2. Почему enum нельзя просто «стереть», как остальные типы?
//    Потому что enum — это не только тип, но и значение (объект) в рантайме.
//    Код вида CheckStatusEnum.Up обращается к этому объекту. Если стереть
//    объявление enum, объекта не будет. Node умеет только стирать типы,
//    а не генерировать код, поэтому enum не поддерживается.
//
// 3. Какой тип получится у `string | number`, и что с ним можно делать без проверок?
//    Тип «строка ИЛИ число». Без проверки — только то, что есть у ОБОИХ
//    (toString(), toLocaleString(), valueOf()). Для методов конкретного типа
//    нужно сначала проверить (typeof) — это narrowing, урок 1.5.
